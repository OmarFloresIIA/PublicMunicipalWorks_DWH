-- Ejercicio 8 - Cambio individual de esquema para IA
-- Propuesta de la issue #11: agrupar propuestas por tema y detectar textos similares.
-- Motor: PostgreSQL. Ejecutar después de db/DDLBASEObPub.sql, sobre una COPIA de la base.
-- Este archivo realiza cambios de esquema; los resultados de IA se guardan en analisis_propuesta_ia.

BEGIN;

-- 1) Catálogo de temas propuestos/clasificados por el modelo.
CREATE TABLE IF NOT EXISTS public.tema_propuesta (
    id_tema          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           varchar(120) NOT NULL UNIQUE,
    palabras_clave   text[] NOT NULL DEFAULT ARRAY[]::text[],
    version_modelo   varchar(100) NOT NULL,
    creado_en        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT tema_propuesta_nombre_no_vacio CHECK (btrim(nombre) <> '')
);

-- 2) Atributos de resumen de la clasificación más reciente en la propuesta.
-- Son NULL para registros históricos que todavía no hayan sido procesados.
ALTER TABLE public.propuestas_obras
    ADD COLUMN IF NOT EXISTS id_tema integer,
    ADD COLUMN IF NOT EXISTS puntaje_pertenencia double precision,
    ADD COLUMN IF NOT EXISTS id_propuesta_similar integer,
    ADD COLUMN IF NOT EXISTS similitud double precision,
    ADD COLUMN IF NOT EXISTS id_region text;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'propuestas_obras_tema_fk'
          AND conrelid = 'public.propuestas_obras'::regclass
    ) THEN
        ALTER TABLE public.propuestas_obras
            ADD CONSTRAINT propuestas_obras_tema_fk
            FOREIGN KEY (id_tema) REFERENCES public.tema_propuesta(id_tema);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'propuestas_obras_similar_fk'
          AND conrelid = 'public.propuestas_obras'::regclass
    ) THEN
        ALTER TABLE public.propuestas_obras
            ADD CONSTRAINT propuestas_obras_similar_fk
            FOREIGN KEY (id_propuesta_similar) REFERENCES public.propuestas_obras(id);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'propuestas_obras_region_fk'
          AND conrelid = 'public.propuestas_obras'::regclass
    ) THEN
        ALTER TABLE public.propuestas_obras
            ADD CONSTRAINT propuestas_obras_region_fk
            FOREIGN KEY (id_region) REFERENCES public.region(id_region);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'propuestas_obras_puntaje_rango_ck'
          AND conrelid = 'public.propuestas_obras'::regclass
    ) THEN
        ALTER TABLE public.propuestas_obras
            ADD CONSTRAINT propuestas_obras_puntaje_rango_ck
            CHECK (puntaje_pertenencia IS NULL OR puntaje_pertenencia BETWEEN 0 AND 1);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'propuestas_obras_similitud_rango_ck'
          AND conrelid = 'public.propuestas_obras'::regclass
    ) THEN
        ALTER TABLE public.propuestas_obras
            ADD CONSTRAINT propuestas_obras_similitud_rango_ck
            CHECK (similitud IS NULL OR similitud BETWEEN 0 AND 1);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'propuestas_obras_no_self_similar_ck'
          AND conrelid = 'public.propuestas_obras'::regclass
    ) THEN
        ALTER TABLE public.propuestas_obras
            ADD CONSTRAINT propuestas_obras_no_self_similar_ck
            CHECK (id_propuesta_similar IS NULL OR id_propuesta_similar <> id);
    END IF;
END $$;

-- 3) Representación vectorial del texto. Se usa double precision[] para no
-- depender de la extensión pgvector. El servicio de IA calcula la similitud
-- y persiste el valor numérico en analisis_propuesta_ia.
CREATE TABLE IF NOT EXISTS public.propuesta_embedding (
    id_embedding     bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_propuesta     integer NOT NULL
                     REFERENCES public.propuestas_obras(id) ON DELETE CASCADE,
    embedding        double precision[] NOT NULL,
    version_modelo   varchar(100) NOT NULL,
    generado_en      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT propuesta_embedding_no_vacio_ck CHECK (cardinality(embedding) > 0),
    CONSTRAINT propuesta_embedding_modelo_uq UNIQUE (id_propuesta, version_modelo)
);

-- 4) Registro histórico de resultados: cada fila representa una salida del
-- modelo para una propuesta concreta. No sobrescribe resultados de versiones previas.
CREATE TABLE IF NOT EXISTS public.analisis_propuesta_ia (
    id_analisis             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_propuesta            integer NOT NULL
                            REFERENCES public.propuestas_obras(id) ON DELETE RESTRICT,
    id_tema                 integer
                            REFERENCES public.tema_propuesta(id_tema),
    id_propuesta_similar    integer
                            REFERENCES public.propuestas_obras(id) ON DELETE RESTRICT,
    tipo_resultado          varchar(40) NOT NULL,
    puntaje_pertenencia     double precision,
    similitud               double precision,
    es_repetida             boolean NOT NULL DEFAULT false,
    fecha_prediccion        timestamptz NOT NULL DEFAULT now(),
    version_modelo          varchar(100) NOT NULL,
    salida_modelo           jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT analisis_propuesta_tipo_ck
        CHECK (tipo_resultado IN ('clasificacion_tema', 'deteccion_similitud')),
    CONSTRAINT analisis_propuesta_puntaje_ck
        CHECK (puntaje_pertenencia IS NULL OR puntaje_pertenencia BETWEEN 0 AND 1),
    CONSTRAINT analisis_propuesta_similitud_ck
        CHECK (similitud IS NULL OR similitud BETWEEN 0 AND 1),
    CONSTRAINT analisis_propuesta_no_self_similar_ck
        CHECK (id_propuesta_similar IS NULL OR id_propuesta_similar <> id_propuesta)
);

CREATE INDEX IF NOT EXISTS idx_analisis_propuesta_fecha
    ON public.analisis_propuesta_ia (id_propuesta, fecha_prediccion DESC);
CREATE INDEX IF NOT EXISTS idx_analisis_propuesta_tipo_fecha
    ON public.analisis_propuesta_ia (tipo_resultado, fecha_prediccion DESC);

COMMIT;

